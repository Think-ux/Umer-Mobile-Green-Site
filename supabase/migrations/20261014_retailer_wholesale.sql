-- Mobile Studio: retailer wholesale foundation
-- Preserve existing customer orders and product pricing.

create table if not exists public.retailer_wholesale_settings (
    id integer primary key default 1 check (id = 1),
    minimum_order_amount numeric(12,2) not null default 5000
        check (minimum_order_amount >= 0),
    enabled boolean not null default false,
    updated_at timestamptz not null default now()
);

insert into public.retailer_wholesale_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.retailer_orders (
    id bigint generated by default as identity primary key,
    retailer_user_id uuid not null references auth.users(id),
    order_number text not null unique,
    status text not null default 'Pending'
        check (status in ('Pending', 'Processing', 'Packed',
                          'Dispatched', 'Delivered', 'Cancelled')),
    subtotal numeric(12,2) not null check (subtotal >= 0),
    total numeric(12,2) not null check (total >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.retailer_order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null
        references public.retailer_orders(id) on delete cascade,
    product_id bigint references public.products(id) on delete set null,
    product_name text not null,
    unit_price numeric(12,2) not null check (unit_price >= 0),
    quantity integer not null check (quantity between 1 and 99),
    discount_percent numeric(5,2) not null default 0
        check (discount_percent between 0 and 100),
    line_total numeric(12,2) not null check (line_total >= 0)
);

create index if not exists retailer_orders_owner_created_idx
    on public.retailer_orders (retailer_user_id, created_at desc);

create index if not exists retailer_order_items_order_idx
    on public.retailer_order_items (order_id);

alter table public.retailer_wholesale_settings enable row level security;
alter table public.retailer_orders enable row level security;
alter table public.retailer_order_items enable row level security;

drop policy if exists "Retailers read own wholesale orders"
    on public.retailer_orders;
create policy "Retailers read own wholesale orders"
    on public.retailer_orders
    for select to authenticated
    using (
        retailer_user_id = (select auth.uid())
        and (select auth.jwt() -> 'app_metadata' ->> 'role') = 'retailer'
    );

drop policy if exists "Retailers read own wholesale order items"
    on public.retailer_order_items;
create policy "Retailers read own wholesale order items"
    on public.retailer_order_items
    for select to authenticated
    using (
        exists (
            select 1
            from public.retailer_orders o
            where o.id = retailer_order_items.order_id
              and o.retailer_user_id = (select auth.uid())
        )
        and (select auth.jwt() -> 'app_metadata' ->> 'role') = 'retailer'
    );

drop policy if exists "Authenticated read wholesale settings"
    on public.retailer_wholesale_settings;
create policy "Authenticated read wholesale settings"
    on public.retailer_wholesale_settings
    for select to authenticated
    using (true);

grant select on public.retailer_wholesale_settings to authenticated;
grant select on public.retailer_orders to authenticated;
grant select on public.retailer_order_items to authenticated;
