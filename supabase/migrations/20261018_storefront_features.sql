alter table public.categories
  add column if not exists parent_id bigint references public.categories(id) on delete restrict;

create or replace function public.enforce_category_hierarchy()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_parent_parent_id bigint;
begin
  if new.parent_id is null then
    return new;
  end if;
  if new.parent_id = new.id then
    raise exception 'A category cannot be its own parent.';
  end if;
  select parent_id into v_parent_parent_id
  from public.categories
  where id = new.parent_id;
  if not found then
    raise exception 'Parent category not found.';
  end if;
  if v_parent_parent_id is not null then
    raise exception 'Subcategories can only be one level deep.';
  end if;
  if exists (select 1 from public.categories where parent_id = new.id) then
    raise exception 'A category with subcategories cannot become a subcategory.';
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_category_hierarchy on public.categories;
create trigger enforce_category_hierarchy
before insert or update of parent_id on public.categories
for each row execute function public.enforce_category_hierarchy();

create or replace function public.move_category(
  p_category_id bigint,
  p_direction integer
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_category_ids bigint[];
  v_current_index integer;
  v_neighbor_index integer;
  v_category_id bigint;
  v_parent_id bigint;
begin
  if (auth.jwt() -> 'app_metadata' ->> 'role') is distinct from 'admin' then
    raise exception 'Only admins can reorder categories.';
  end if;
  if p_direction not in (-1, 1) then
    raise exception 'Choose a valid category direction.';
  end if;

  select parent_id into v_parent_id
  from public.categories
  where id = p_category_id
  for update;
  if not found then
    raise exception 'Category not found.';
  end if;
  perform 1 from public.categories
  where parent_id is not distinct from v_parent_id
  for update;
  select array_agg(id order by sort_order, id)
  into v_category_ids
  from public.categories
  where parent_id is not distinct from v_parent_id;
  v_current_index := array_position(v_category_ids, p_category_id);
  if v_current_index is null then
    raise exception 'Category not found.';
  end if;

  v_neighbor_index := v_current_index + p_direction;
  if v_neighbor_index < 1 or v_neighbor_index > array_length(v_category_ids, 1) then
    return;
  end if;
  v_category_id := v_category_ids[v_current_index];
  v_category_ids[v_current_index] := v_category_ids[v_neighbor_index];
  v_category_ids[v_neighbor_index] := v_category_id;

  update public.categories as category
  set sort_order = ordered.ordinal::integer,
      updated_at = now()
  from unnest(v_category_ids) with ordinality as ordered(id, ordinal)
  where category.id = ordered.id;
end;
$$;

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null check (
    char_length(email) between 3 and 254
    and email = lower(trim(email))
    and email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
  ),
  consented_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create unique index if not exists newsletter_subscribers_email_key
  on public.newsletter_subscribers (email);

create or replace function public.subscribe_newsletter(p_email text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
begin
  if char_length(v_email) not between 3 and 254
     or v_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then
    raise exception 'Enter a valid email address.';
  end if;
  insert into public.newsletter_subscribers (email)
  values (v_email)
  on conflict (email) do nothing;
  return jsonb_build_object('subscribed', true);
end;
$$;

alter table public.newsletter_subscribers enable row level security;
revoke all on table public.newsletter_subscribers from anon, authenticated;
grant select, delete on public.newsletter_subscribers to authenticated;
drop policy if exists "Admins manage newsletter subscribers" on public.newsletter_subscribers;
create policy "Admins manage newsletter subscribers"
  on public.newsletter_subscribers for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
revoke all on function public.subscribe_newsletter(text) from public;
grant execute on function public.subscribe_newsletter(text) to anon, authenticated;

create or replace function public.create_verified_customer_order(
  p_name text,
  p_phone text,
  p_address text,
  p_city text,
  p_items jsonb,
  p_preferred_courier text default 'store_choice',
  p_fulfillment_method text default 'delivery',
  p_area text default '',
  p_expected_delivery numeric default null,
  p_payment_method text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_verified_phone text := regexp_replace(coalesce(auth.jwt() ->> 'phone', ''), '[^0-9]', '', 'g');
  v_requested_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
begin
  if auth.uid() is null
     or coalesce(auth.jwt() ->> 'is_anonymous', 'false') <> 'false'
     or v_verified_phone = '' then
    raise exception 'Verify your mobile number before placing an order.';
  end if;
  if length(v_verified_phone) = 12 and left(v_verified_phone, 2) = '92' then
    v_verified_phone := '0' || substr(v_verified_phone, 3);
  end if;
  if v_verified_phone <> v_requested_phone then
    raise exception 'The verified mobile number does not match the order contact number.';
  end if;
  return public.create_customer_order(
    p_name, p_phone, p_address, p_city, p_items, p_preferred_courier,
    p_fulfillment_method, p_area, p_expected_delivery, p_payment_method
  );
end;
$$;

revoke all on function public.create_customer_order(text, text, text, text, jsonb, text, text, text, numeric, text) from public, anon, authenticated;
revoke all on function public.create_verified_customer_order(text, text, text, text, jsonb, text, text, text, numeric, text) from public, anon;
grant execute on function public.create_verified_customer_order(text, text, text, text, jsonb, text, text, text, numeric, text) to authenticated;
